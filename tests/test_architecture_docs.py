"""Architecture documentation (arc42, docs/architecture/arc42/): its diagrams are Arcviz documents.

Spec: docs/architecture/specs/architecture-documentation.md, ADR-0040. The C4, deployment and runtime views are
`docs/architecture/diagrams/*.arcviz.json`, rendered by `scripts/render_architecture_diagrams.py` with
Arcviz's own renderer of their type into `<name>.mmd` (Mermaid, included as snippets) or `<name>.svg` (sequence
diagrams, shown as images) next to them.
"""

import ast
import importlib.util
import json
import re
from pathlib import Path

import pytest

from arcviz import exchange
from arcviz.model import BUILTIN_KINDS, active_kinds

ROOT = Path(__file__).parent.parent
DIAGRAMS = ROOT / "docs" / "architecture" / "diagrams"
ARC42 = ROOT / "docs" / "architecture" / "arc42"

_spec = importlib.util.spec_from_file_location(
    "render_architecture_diagrams", ROOT / "scripts" / "render_architecture_diagrams.py"
)
assert _spec and _spec.loader
generator = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(generator)

SOURCES = sorted(DIAGRAMS.glob("*.arcviz.json"))


def _stem(path: Path) -> str:
    return path.name.removesuffix(".arcviz.json")


def test_there_are_c4_deployment_and_runtime_views():
    names = {_stem(p) for p in SOURCES}
    assert {"c4-context", "c4-containers", "c4-components-server", "c4-components-web-ui", "deployment"} <= names
    runtime = {"chat-turn", "project-chat-turn", "direct-edit", "propose-confirm", "review"}
    assert {f"runtime-{name}" for name in runtime} <= names


def test_rendered_diagrams_are_up_to_date():
    """Fails when a .arcviz.json changed without re-running the generator (or the renderer changed)."""
    stale = generator.stale(generator.render_all())
    assert not stale, f"Out of date, run `make diagrams`: {', '.join(stale)}"


def test_render_all_restores_the_active_kind_catalogue():
    generator.render_all()
    assert active_kinds() is BUILTIN_KINDS


def test_no_orphaned_renders():
    sources = {_stem(p) for p in SOURCES}
    renders = [p.stem for p in [*DIAGRAMS.glob("*.mmd"), *DIAGRAMS.glob("*.svg")]]
    assert sorted(renders) == sorted(sources)


def test_rendered_file_names_its_source_and_is_marked_generated():
    text = (DIAGRAMS / "c4-context.mmd").read_text(encoding="utf-8")
    assert text.startswith("flowchart ")
    assert "%% Generated by scripts/render_architecture_diagrams.py from c4-context.arcviz.json" in text
    svg = (DIAGRAMS / "runtime-review.svg").read_text(encoding="utf-8")
    assert svg.startswith("<!-- Generated by scripts/render_architecture_diagrams.py from runtime-review.arcviz.json")
    assert '<svg xmlns="http://www.w3.org/2000/svg" class="arcviz-seq"' in svg


@pytest.mark.parametrize("source", SOURCES, ids=_stem)
def test_sources_are_importable_documents_with_the_c4_kinds(source):
    """Each source is an ordinary export: the app imports it when started with the C4 kinds file."""
    document = json.loads(source.read_text(encoding="utf-8"))
    assert document["format"] == exchange.FORMAT
    with generator.c4_kinds():
        exchange.parse_document(document)


@pytest.mark.parametrize("source", SOURCES, ids=_stem)
def test_every_diagram_is_shown_on_an_arc42_page(source):
    snippet = f'--8<-- "docs/architecture/diagrams/{_stem(source)}.mmd"'  # Mermaid renders: a snippet
    image = f"](../diagrams/{_stem(source)}.svg)"  # SVG renders: an image
    pages = [p for p in ARC42.glob("*.md") if any(ref in p.read_text(encoding="utf-8") for ref in (snippet, image))]
    assert pages, f"{_stem(source)} is not included in any page under docs/architecture/arc42/"


@pytest.mark.parametrize("source", SOURCES, ids=_stem)
def test_code_and_doc_references_in_diagrams_exist(source):
    """Elements point at the code (`code`) and docs (`spec`) they stand for; stale paths fail."""
    diagram = json.loads(source.read_text(encoding="utf-8"))["diagram"]
    for node in diagram["nodes"].values():
        for key in ("code", "spec"):
            for ref in filter(None, re.split(r",\s*", node["properties"].get(key, ""))):
                assert (ROOT / ref.split("#")[0]).exists(), f"{_stem(source)}: {node['id']}.{key} -> {ref}"


RUNTIME = sorted(p for p in SOURCES if _stem(p).startswith("runtime-"))


@pytest.mark.parametrize("source", RUNTIME, ids=_stem)
def test_runtime_views_are_sequence_diagrams_of_the_server_components(source):
    """Each lifeline id names a building block of the server component view (`<id>` or `<id>:<qualifier>`)."""
    diagram = exchange.parse_document(json.loads(source.read_text(encoding="utf-8")))
    assert diagram.type == "sequence" and diagram.interaction is not None
    components = json.loads((DIAGRAMS / "c4-components-server.arcviz.json").read_text(encoding="utf-8"))
    known = set(components["diagram"]["nodes"])
    for lifeline in diagram.interaction.lifelines:
        assert lifeline.id.split(":")[0] in known, f"{_stem(source)}: lifeline {lifeline.id} is no building block"


@pytest.mark.parametrize("source", RUNTIME, ids=_stem)
def test_runtime_views_have_no_risk_findings(source):
    """The behaviour rules (#123) find no reply without a call and the like in the runtime views."""
    from arcviz import rules

    diagram = exchange.parse_document(json.loads(source.read_text(encoding="utf-8")))
    assert [f.id for f in rules.run_checks(diagram) if f.category == "risk"] == []


def _module(code: str) -> str:
    """'arcviz/agent.py' -> 'arcviz.agent', 'arcviz/llm/' -> 'arcviz.llm'."""
    return code.removesuffix("/").removesuffix(".py").replace("/", ".")


def _imports(code: str) -> set[str]:
    """Absolute names of the package modules imported anywhere (also lazily) in a file or package."""
    path = ROOT / code
    out: set[str] = set()
    for file in sorted(path.rglob("*.py")) if path.is_dir() else [path]:
        package = _module(file.relative_to(ROOT).as_posix()).rsplit(".", 1)[0]
        for node in ast.walk(ast.parse(file.read_text(encoding="utf-8"))):
            if isinstance(node, ast.ImportFrom) and node.level:
                base = package.rsplit(".", node.level - 1)[0] if node.level > 1 else package
                if node.module:
                    out.add(f"{base}.{node.module}")
                else:
                    out.update(f"{base}.{alias.name}" for alias in node.names)
    return out


def test_server_component_view_matches_the_imports():
    """The dependency edges of the server component view are exactly the imports between its components.

    Edges to model.py are left out on purpose (every module but llm/ imports it); the page says so.
    """
    diagram = json.loads((DIAGRAMS / "c4-components-server.arcviz.json").read_text(encoding="utf-8"))["diagram"]
    modules = {
        node_id: _module(node["properties"]["code"])
        for node_id, node in diagram["nodes"].items()
        if node["kind"] == "component" and node["properties"].get("code", "").startswith("arcviz/")
    }

    def component(name: str) -> str | None:
        matches = [nid for nid, mod in modules.items() if name == mod or name.startswith(mod + ".")]
        return max(matches, key=lambda nid: len(modules[nid]), default=None)

    actual = {
        (source, target)
        for source, node in diagram["nodes"].items()
        if source in modules
        for name in _imports(node["properties"]["code"])
        if (target := component(name)) not in (None, source, "model")
    }
    drawn = {(e["source"], e["target"]) for e in diagram["edges"] if e["kind"] == "dependency"}
    assert drawn == actual, f"missing: {sorted(actual - drawn)}, not imported: {sorted(drawn - actual)}"


