"""Render the architecture diagrams (Arcviz documents) into Mermaid snippets for the docs.

Usage: python scripts/render_architecture_diagrams.py [--check]

Every ``docs/architecture/diagrams/<name>.arcviz.json`` is an ordinary Arcviz export (import it into the
app to edit it, export it back). This script validates it with ``exchange.parse_document`` and renders it
with the renderer of its diagram type (``render.renderer_for``): Mermaid types (the C4 and deployment views)
into ``<name>.mmd``, which the arc42 pages include inside a ``mermaid`` fence as a snippet; sequence diagrams
(the runtime views, #120) with the own SVG renderer into ``<name>.svg``, which the pages show as an image. The
C4 element kinds come from ``c4-kinds.json`` in the same directory, the kinds file the app reads from
``ARCVIZ_KINDS_FILE`` (ADR-0040).

``--check`` writes nothing and exits 1 if a rendered file is missing or out of date
(``tests/test_architecture_docs.py`` does the same in pytest).
"""

from __future__ import annotations

import json
import sys
from collections.abc import Iterator
from contextlib import contextmanager
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from arcviz import exchange, render  # noqa: E402
from arcviz.kinds import load_kind_catalog  # noqa: E402
from arcviz.model import active_kinds, use_kinds  # noqa: E402

DIAGRAMS = ROOT / "docs" / "architecture" / "diagrams"
KINDS_FILE = DIAGRAMS / "c4-kinds.json"
SUFFIX = ".arcviz.json"


@contextmanager
def c4_kinds() -> Iterator[None]:
    """Activate the C4 kinds file for the duration of the block, then restore the previous catalogue."""
    previous = active_kinds()
    use_kinds(load_kind_catalog(KINDS_FILE))
    try:
        yield
    finally:
        use_kinds(previous)


EXTENSIONS = {"mermaid": ".mmd", "svg": ".svg"}  # file of each render format


def render_document(source: Path) -> tuple[str, str]:
    """(file extension, text) of one diagram document rendered by its type's renderer, with a header naming the
    generator and the source."""
    diagram = exchange.parse_document(json.loads(source.read_text(encoding="utf-8")))
    payload = render.payload(diagram)
    text = payload[payload["renderer"]]
    note = f"Generated by scripts/render_architecture_diagrams.py from {source.name}. Do not edit."
    if payload["renderer"] == "mermaid":
        first, rest = text.split("\n", 1)
        return EXTENSIONS["mermaid"], f"{first}\n%% {note}\n{rest}"
    return EXTENSIONS["svg"], f"<!-- {note} -->\n{text}\n"


def render_all() -> dict[Path, str]:
    """Target path (``<name>.mmd`` or ``<name>.svg``) -> rendered text for every diagram document."""
    out: dict[Path, str] = {}
    with c4_kinds():
        for source in sorted(DIAGRAMS.glob("*" + SUFFIX)):
            extension, text = render_document(source)
            out[source.with_name(source.name.removesuffix(SUFFIX) + extension)] = text
    return out


def stale(rendered: dict[Path, str]) -> list[str]:
    """Names of the rendered files that are missing or differ from what is on disk."""
    return [
        target.name
        for target, text in rendered.items()
        if not target.is_file() or target.read_text(encoding="utf-8") != text
    ]


def main(argv: list[str]) -> int:
    rendered = render_all()
    outdated = stale(rendered)
    if "--check" in argv:
        for name in outdated:
            print(f"out of date: docs/architecture/diagrams/{name}", file=sys.stderr)
        return 1 if outdated else 0
    for target, text in rendered.items():
        if target.name in outdated:
            target.write_text(text, encoding="utf-8")
            print(f"wrote {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
